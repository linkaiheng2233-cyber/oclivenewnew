import type { Page } from '@playwright/test'
import { expect, test } from '@playwright/test'
import { gotoApp, unlockWin98 } from './helpers'

async function openRoleImport(page: Page) {
  await page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true }).click()
  const settings = page.locator('.sv-dialog')
  await settings.locator('[data-settings-page=roles]').click()
  return settings
}

test('IME candidate confirmation keeps the draft until a separate Enter sends it', async ({ page }) => {
  await gotoApp(page)
  const input = page.locator('#chat-user-message')
  await input.fill('中文输入保持完整')
  await input.dispatchEvent('keydown', { key: 'Enter', isComposing: true, keyCode: 229 })
  await expect(input).toHaveValue('中文输入保持完整')
  await expect(page.locator('.workspace-messages')).not.toContainText('Echo: 中文输入保持完整')
  await input.press('Enter')
  await expect(page.locator('.workspace-messages')).toContainText('Echo: 中文输入保持完整')
})

test('a failed model configuration read can retry inside the same window', async ({ page }) => {
  await gotoApp(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.get_llm_user_settings', JSON.stringify({ code: 'IO_ERROR', message: 'temporary settings read failure' })))
  await page.locator('.nav-global').getByRole('button', { name: 'Models & connection', exact: true }).click()
  const model = page.locator('.mm-dialog')
  const failure = model.locator('.mm-load-error')
  await expect(failure).toContainText('Model settings could not be loaded')
  await expect(model.getByRole('button', { name: 'Save & apply', exact: true })).toHaveCount(0)
  await page.evaluate(() => localStorage.removeItem('oclive.e2e.fail.get_llm_user_settings'))
  await failure.getByRole('button', { name: 'Retry loading settings', exact: true }).click()
  await expect(failure).toHaveCount(0)
  await expect(model.getByRole('button', { name: 'Save & apply', exact: true })).toBeEnabled()
  await expect(model.locator('.mm-root')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(page.locator('#chat-user-message')).toBeVisible()
})

test('cancelling the native source picker leaves role settings usable', async ({ page }) => {
  await gotoApp(page)
  const settings = await openRoleImport(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.dialog.open', 'null'))
  await settings.locator('.pack-bar button').nth(1).click()
  await expect(page.locator('.modal-backdrop')).toHaveCount(0)
  await expect(settings.locator('.pack-bar button').nth(1)).toBeEnabled()
  await page.keyboard.press('Escape')
  await expect(settings).toHaveCount(0)
})

test('a role package read failure keeps settings usable for a new import attempt', async ({ page }) => {
  await gotoApp(page)
  const settings = await openRoleImport(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.peek_role_pack_command', JSON.stringify({ code: 'IO_ERROR', message: 'cannot read selected role package api_key=private-import-fixture', once: true })))
  const importButton = settings.locator('.pack-bar button').nth(1)
  await importButton.click()
  const toast = page.locator('.toast')
  await expect(toast).toContainText('file operation failed')
  await toast.getByText('Technical details', { exact: true }).click()
  await expect(toast.locator('pre')).toContainText('cannot read selected role package')
  await expect(toast).not.toContainText('private-import-fixture')
  await toast.getByRole('button', { name: 'Dismiss notification', exact: true }).click()
  await importButton.click()
  const conflict = page.getByRole('dialog').filter({ has: page.locator('#pack-conflict-title') })
  await conflict.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(settings).toBeVisible()
})

for (const skin of ['default', 'win98']) {
  test(`existing role confirmation stays above settings and traps focus in ${skin}`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width: skin === 'win98' ? 430 : 800, height: 600 })
    await gotoApp(page)
    if (skin === 'win98')
      await unlockWin98(page)
    const settings = await openRoleImport(page)
    const importButton = settings.locator('.pack-bar button').nth(1)
    await importButton.click()
    const conflict = page.getByRole('dialog').filter({ has: page.locator('#pack-conflict-title') })
    await expect(conflict).toBeVisible()
    const cancel = conflict.getByRole('button', { name: 'Cancel', exact: true })
    await page.screenshot({ path: testInfo.outputPath(`role-import-conflict-${skin}.png`) })
    await cancel.click({ timeout: 3000 })
    await expect(conflict).toHaveCount(0)
    await expect(importButton).toBeFocused()
    await importButton.click()
    await expect(cancel).toBeFocused()
    await page.keyboard.press('Shift+Tab')
    await expect(conflict.locator('.btn-danger')).toBeFocused()
    await page.keyboard.press('Tab')
    await expect(cancel).toBeFocused()
    await page.keyboard.press('Escape')
    await expect(conflict).toHaveCount(0)
    await expect(settings).toBeVisible()
    await expect(importButton).toBeFocused()
  })
}

test('import progress covers settings and keeps focus until installation finishes', async ({ page }) => {
  await gotoApp(page)
  const settings = await openRoleImport(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.holdImport', '1'))
  await settings.locator('.pack-bar button').nth(1).click()
  const conflict = page.getByRole('dialog').filter({ has: page.locator('#pack-conflict-title') })
  // Clickability of the confirmation is covered above; Enter also exercises the keyboard path.
  await conflict.locator('.btn-danger').focus()
  await page.keyboard.press('Enter')
  const progress = page.getByRole('dialog').filter({ has: page.locator('.bar-track') })
  await expect(progress).toHaveAttribute('aria-busy', 'true')
  expect(await progress.evaluate((element) => {
    const card = element.querySelector('.modal-card')!
    const bounds = card.getBoundingClientRect()
    return element.contains(document.elementFromPoint(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2))
  })).toBe(true)
  await page.keyboard.press('Tab')
  await expect(progress.locator('.modal-card')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(progress).toBeVisible()
  await page.evaluate(() => window.dispatchEvent(new Event('oclive:e2e:release-import')))
  await expect(progress).toHaveCount(0)
  await expect(conflict).toHaveCount(0)
  await expect(settings).toBeVisible()
  await expect(settings.locator('[data-settings-page=roles]')).toHaveAttribute('aria-current', 'page')
})

test('a completed reply does not take keyboard focus away from settings', async ({ page }) => {
  await gotoApp(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.holdSend', '1'))
  await page.locator('#chat-user-message').fill('reply while I adjust my settings')
  await page.locator('#chat-user-message').press('Enter')
  await expect(page.locator('.stop-button')).toBeVisible()
  await page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true }).click()
  const settings = page.locator('.sv-dialog')
  const chatPage = settings.locator('[data-settings-page=chat]')
  await chatPage.click()
  await page.evaluate(() => window.dispatchEvent(new Event('oclive:e2e:release-send')))
  await expect(page.locator('.workspace-messages')).toContainText('Echo: reply while I adjust my settings')
  await expect(chatPage).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(settings).toHaveCount(0)
})
