import { expect, test } from '@playwright/test'
import { gotoApp } from './helpers'

test('Help keeps dismissed errors and exposes searchable, redacted runtime logs', async ({ page }) => {
  await gotoApp(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.send_message', JSON.stringify({ code: 'LLM_ERROR', message: 'support test diagnostic api_key=private-key-fixture', once: true })))
  await page.locator('#chat-user-message').fill('diagnostic path')
  await page.locator('#chat-user-message').press('Enter')
  await page.locator('.toast').getByRole('button', { name: 'Dismiss notification' }).click()
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: /Recent errors/ }).click()
  await expect(dialog.locator('.support-history')).toContainText('model could not reply')
  await expect(dialog.locator('.support-history')).toContainText('send_message')
  await dialog.locator('.support-history summary').first().click()
  await expect(dialog.locator('.support-history')).toContainText('LLM_ERROR')
  await expect(dialog).not.toContainText('private-key-fixture')
  await dialog.getByRole('tab', { name: 'Runtime logs' }).click()
  await expect(dialog.locator('.support-log-line')).toHaveCount(3)
  await expect(dialog).not.toContainText('fixture-secret')
  await dialog.getByLabel('Level', { exact: true }).selectOption('error')
  await expect(dialog.locator('.support-log-line')).toHaveCount(1)
  await dialog.getByRole('searchbox').fill('missing')
  await expect(dialog).toContainText('No matching lines')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.locator('#chat-user-message')).toBeVisible()
})

test('log read errors remain retryable without closing help', async ({ page }) => {
  await gotoApp(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.read_support_logs', JSON.stringify({ code: 'IO_ERROR', message: 'test log file locked', once: true })))
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('.error-notice')).toBeVisible()
  await dialog.getByRole('tab', { name: 'Runtime logs' }).click()
  await dialog.getByRole('button', { name: 'Refresh logs', exact: true }).click()
  await expect(dialog.locator('.support-log-line')).toHaveCount(3)
  await expect(dialog.locator('.error-notice')).toHaveCount(0)
})

test('model list errors open Help above the model form and return without discarding edits', async ({ page }, testInfo) => {
  await gotoApp(page)
  const draft = page.locator('#chat-user-message')
  await draft.fill('keep this chat draft while diagnosing a model')
  const opener = page.locator('.nav-global').getByRole('button', { name: 'Models & connection', exact: true })
  await opener.click()
  const model = page.locator('.mm-dialog')
  const address = model.getByRole('textbox', { name: 'Ollama base URL', exact: true })
  await address.fill('http://not-running.test:11434')
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.list_ollama_models', JSON.stringify({ code: 'LLM_ERROR', message: 'Failed to list models api_key=private-list-key', once: true })))
  const refresh = model.getByRole('button', { name: 'Refresh Ollama list', exact: true }).last()
  await refresh.click()
  const noticeText = await page.locator('.toast').textContent()
  await page.locator('.toast').getByRole('button', { name: 'Open Help & recovery', exact: true }).click()
  const help = page.locator('.workspace-help')
  await expect(help).toBeFocused()
  await help.getByRole('tab', { name: /Recent errors/ }).click()
  await expect(help.locator('.support-history')).toContainText('list_ollama_models')
  await expect(help).not.toContainText('private-list-key')
  await page.screenshot({ path: testInfo.outputPath('model-error-help-foreground.png') })
  await help.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(model).toBeFocused()
  await expect(address).toHaveValue('http://not-running.test:11434')
  expect(noticeText).toContain('Could not load the Ollama model list')
  await expect(model.locator('.mm-status')).toHaveAttribute('data-state', 'error')
  await refresh.click()
  await expect(model.locator('.mm-status')).toHaveAttribute('data-state', 'ready')
  await page.keyboard.press('Escape')
  await expect(opener).toBeFocused()
  await expect(draft).toHaveValue('keep this chat draft while diagnosing a model')
})

test('settings errors open Help in front and return to the same settings page for retry', async ({ page }, testInfo) => {
  await gotoApp(page)
  const opener = page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true })
  await opener.click()
  const settings = page.locator('.sv-dialog')
  const connection = settings.locator('[data-settings-page=connection]')
  await connection.click()
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.run_environment_diagnostics', JSON.stringify({ code: 'IO_ERROR', message: 'test diagnostic unavailable', once: true })))
  await settings.getByRole('button', { name: 'Run check', exact: true }).click()
  const notice = settings.locator('.sv-general-page > .error-notice')
  await expect(notice).toContainText('environment check could not finish')
  await page.locator('.toast').getByRole('button', { name: 'Open Help & recovery', exact: true }).click()
  const help = page.locator('.workspace-help')
  await expect(help).toBeFocused()
  await help.getByRole('tab', { name: 'Runtime logs', exact: true }).click()
  await expect(help.locator('.support-log-line')).toHaveCount(3)
  await page.keyboard.press('Escape')
  await expect(help).toHaveCount(0)
  await expect(settings).toBeFocused()
  await expect(connection).toHaveAttribute('aria-current', 'page')
  await notice.getByRole('button', { name: 'Retry this action' }).click()
  await expect(notice).toHaveCount(0)
  await expect(settings.locator('.sv-env-results')).toBeVisible()
  await expect(settings.locator('.sv-general-page')).toBeFocused()
  await testInfo.attach('settings-focus-after-retry', {
    body: JSON.stringify(await page.evaluate(() => ({
      activeElement: document.activeElement?.outerHTML,
      settingsVisible: !!document.querySelector('.sv-dialog'),
    }))),
    contentType: 'application/json',
  })
  await page.keyboard.press('Escape')
  await expect(settings).toHaveCount(0)
  await expect(opener).toBeFocused()
})
