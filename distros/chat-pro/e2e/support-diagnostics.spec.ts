import { expect, test } from '@playwright/test'
import { gotoApp } from './helpers'

test('Help keeps dismissed errors and exposes searchable, redacted runtime logs', async ({ page }) => {
  await gotoApp(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.send_message', JSON.stringify({ code: 'LLM_ERROR', message: 'support test diagnostic api_key=private-key-fixture', once: true })))
  await page.locator('#chat-user-message').fill('diagnostic path')
  await page.locator('#chat-user-message').press('Enter')
  await page.locator('.toast').getByRole('button', { name: 'Dismiss notification' }).click()
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('tab', { name: /Recent errors/ }).click()
  await expect(dialog.locator('.support-history')).toContainText('model could not reply')
  await expect(dialog.locator('.support-history')).toContainText('send_message')
  await dialog.locator('.support-history summary').first().click()
  await expect(dialog.locator('.support-history')).toContainText('LLM_ERROR')
  await expect(dialog).not.toContainText('private-key-fixture')
  await dialog.getByRole('tab', { name: 'Runtime logs' }).click()
  await expect(dialog.locator('.support-log-line')).toHaveCount(3)
  await expect(dialog).not.toContainText('fixture-secret')
  await dialog.getByLabel('Level', { exact: true }).selectOption('error')
  await expect(dialog.locator('.support-log-line')).toHaveCount(1)
  await dialog.getByRole('searchbox').fill('missing')
  await expect(dialog).toContainText('No matching lines')
  await dialog.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(page.locator('#chat-user-message')).toBeVisible()
})

test('log read errors remain retryable without closing help', async ({ page }) => {
  await gotoApp(page)
  await page.evaluate(() => localStorage.setItem('oclive.e2e.fail.read_support_logs', JSON.stringify({ code: 'IO_ERROR', message: 'test log file locked', once: true })))
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog.locator('.error-notice')).toBeVisible()
  await dialog.getByRole('tab', { name: 'Runtime logs' }).click()
  await dialog.getByRole('button', { name: 'Refresh logs', exact: true }).click()
  await expect(dialog.locator('.support-log-line')).toHaveCount(3)
  await expect(dialog.locator('.error-notice')).toHaveCount(0)
})
