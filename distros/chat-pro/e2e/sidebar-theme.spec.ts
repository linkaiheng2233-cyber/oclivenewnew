import { readFileSync } from 'node:fs'
import { expect, test } from '@playwright/test'
import { gotoApp } from './helpers'

test('sidebar thumbnails crop role art, keep names accessible and fall back for missing pictures', async ({ page }, testInfo) => {
  const portrait = `data:image/png;base64,${readFileSync(new URL('../roles/mumu/assets/images/normal-v2.png', import.meta.url)).toString('base64')}`
  await page.addInitScript(portrait => localStorage.setItem('oclive.e2e.portrait.role-a', portrait), portrait)
  await page.setViewportSize({ width: 1440, height: 960 })
  await gotoApp(page)
  const first = page.locator('.nav-role').first()
  await expect(first.getByRole('button', { name: 'Role Alpha', exact: true })).toBeVisible()
  const image = first.locator('.hero--thumbnail img')
  await expect.poll(() => image.evaluate((element: HTMLImageElement) => element.complete && element.naturalWidth > 0)).toBe(true)
  await expect(image).toHaveCSS('object-fit', 'cover')
  await expect(first.locator('.role-initial')).toHaveCSS('width', '32px')
  await expect(page.locator('.nav-role').nth(1).locator('.avatar-fallback')).toHaveText('R')
  await page.screenshot({ path: testInfo.outputPath('sidebar-thumbnails.png') })
  await page.setViewportSize({ width: 430, height: 860 })
  await expect(first.locator('.role-initial')).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.locator('.nav-role').nth(1).getByRole('button', { name: 'Role Beta', exact: true }).click()
  await expect(page.locator('.workspace-header h1')).toContainText('Role Beta')
  await expect(first.getByRole('button', { name: 'Role Alpha', exact: true })).toBeEnabled()
  await expect(first.locator('img')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('sidebar-narrow.png') })
})

test('quick dark mode stays synchronized with Settings, system appearance and reload', async ({ page }, testInfo) => {
  await page.emulateMedia({ colorScheme: 'light' })
  await gotoApp(page)
  const toggle = page.getByRole('switch', { name: 'Dark mode', exact: true })
  await page.locator('#chat-user-message').fill('keep this draft while changing theme')
  await expect(toggle).not.toBeChecked()
  await toggle.click()
  await expect(toggle).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  expect(await page.evaluate(() => localStorage.getItem('oclive-runtime-theme'))).toBe('dark')
  await page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true }).click()
  const settings = page.locator('.sv-dialog')
  await expect(settings.getByRole('button', { name: 'Dark', exact: true })).toBeVisible()
  await settings.getByRole('button', { name: 'Dark', exact: true }).click()
  await expect(settings.getByRole('button', { name: 'Match system', exact: true })).toBeVisible()
  await expect(toggle).not.toBeChecked()
  await page.emulateMedia({ colorScheme: 'dark' })
  await expect(toggle).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.keyboard.press('Escape')
  await expect(page.locator('#chat-user-message')).toHaveValue('keep this draft while changing theme')
  await toggle.focus()
  await page.keyboard.press('Space')
  await expect(toggle).not.toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await toggle.click()
  await page.screenshot({ path: testInfo.outputPath('quick-dark-mode.png') })
  await page.reload()
  await expect(toggle).toBeChecked()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true }).click()
  await expect(settings.getByRole('button', { name: 'Dark', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await page.setViewportSize({ width: 430, height: 860 })
  await expect(toggle).toBeInViewport()
  await toggle.click()
  await expect(toggle).not.toBeChecked()
  await page.screenshot({ path: testInfo.outputPath('quick-theme-narrow.png') })
})

test('the classic skin keeps its colors and explains why the light/dark control is unavailable', async ({ page }) => {
  await gotoApp(page)
  const toggle = page.getByRole('switch', { name: 'Dark mode', exact: true })
  await page.locator('.workspace-header h1').click()
  for (const key of ['ArrowUp', 'ArrowUp', 'ArrowDown', 'ArrowDown', 'ArrowLeft', 'ArrowRight', 'ArrowLeft', 'ArrowRight', 'b', 'a'])
    await page.keyboard.press(key)
  await expect(toggle).toBeDisabled()
  await expect(toggle).toHaveAttribute('title', /Win98 uses classic colors/)
  await page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true }).click()
  await page.locator('.sv-dialog').getByRole('switch', { name: /Windows 98|Win98/ }).uncheck()
  await page.keyboard.press('Escape')
  await expect(toggle).toBeEnabled()
  await toggle.click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
})
