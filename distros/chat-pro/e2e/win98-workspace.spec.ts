import type { Page } from '@playwright/test'
import { expect, test } from '@playwright/test'
import { gotoApp } from './helpers'

async function unlock(page: Page) {
  await page.locator('.workspace-header h1').click()
  for (const key of ['ArrowUp', 'ArrowUp', 'ArrowDown', 'ArrowDown', 'ArrowLeft', 'ArrowRight', 'ArrowLeft', 'ArrowRight', 'b', 'a'])
    await page.keyboard.press(key)
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'win98')
}

async function appearance(page: Page) {
  await page.locator('.nav-global').getByRole('button', { name: 'App settings', exact: true }).click()
  const dialog = page.locator('.sv-dialog')
  await dialog.locator('[data-settings-page=appearance]').click()
  return dialog
}

test('discovery skins the library and model guide, then restores their exact default styles', async ({ page }, testInfo) => {
  await page.addInitScript(() => localStorage.setItem('oclive-runtime-theme', 'dark'))
  await gotoApp(page)
  await page.locator('nav').getByRole('button', { name: 'Role library', exact: true }).click()
  const card = page.locator('.role-card').first()
  const defaultRadius = await card.evaluate(element => getComputedStyle(element).borderRadius)
  const defaultBackground = await card.evaluate(element => getComputedStyle(element).backgroundColor)
  await expect(page.locator('.model-setup')).toBeVisible()
  await unlock(page)
  await expect(card).toHaveCSS('border-radius', '0px')
  await expect(card).toHaveCSS('border-top-style', 'outset')
  await expect(page.locator('.model-setup')).toHaveCSS('border-radius', '0px')
  await expect(page.locator('.library-tools .pack-bar .btn').first()).toHaveCSS('border-radius', '0px')
  await expect(page.locator('.kernel-status')).toHaveCSS('border-radius', '0px')
  await expect(page.locator('.role-nav .nav-button.active')).toHaveCSS('color', 'rgb(255, 255, 255)')
  await expect(page.locator('.win98-titlebar')).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('win98-library.png') })
  const settings = await appearance(page)
  const toggle = settings.getByRole('switch', { name: /Windows 98/ })
  await expect(toggle).toBeChecked()
  await expect(settings.locator('.ui-select').first()).toHaveCSS('border-radius', '0px')
  await expect(settings.locator('.sv-content .ui-btn').first()).toHaveCSS('border-top-style', 'outset')
  await expect(page.locator('.sv-backdrop')).toHaveCSS('backdrop-filter', 'none')
  await page.screenshot({ path: testInfo.outputPath('win98-settings.png') })
  await toggle.uncheck()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'default')
  await settings.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(card).toHaveCSS('border-radius', defaultRadius)
  await expect(card).toHaveCSS('background-color', defaultBackground)
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await expect(page.locator('.win98-titlebar')).toHaveCount(0)
  await page.screenshot({ path: testInfo.outputPath('default-library-restored.png') })
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  await expect(page.locator('.workspace-help')).toHaveCSS('border-radius', '16px')
  await page.locator('.workspace-help').getByRole('button', { name: 'Close', exact: true }).click()
})

test('skin changes preserve a chat draft and replies, and recovery uses classic readable chrome', async ({ page }, testInfo) => {
  await gotoApp(page)
  const input = page.locator('#chat-user-message')
  await input.fill('a retained conversation')
  await input.press('Enter')
  await expect(page.locator('.workspace-messages')).toContainText('Echo: a retained conversation')
  await input.fill('my unsent draft')
  await unlock(page)
  await expect(input).toHaveValue('my unsent draft')
  await expect(page.locator('.workspace-composer .send')).toHaveCSS('color', 'rgb(0, 0, 0)')
  await expect(page.locator('.workspace-messages')).toContainText('Echo: a retained conversation')
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  const help = page.locator('.workspace-help')
  await expect(help).toHaveCSS('border-radius', '0px')
  await expect(page.locator('.workspace-modal-backdrop')).toHaveCSS('backdrop-filter', 'none')
  await help.getByRole('tab', { name: 'Runtime logs' }).click()
  await expect(help.locator('.support-log-view')).toHaveCSS('border-radius', '0px')
  await expect(help.locator('.support-tabs button[aria-selected=true]')).toHaveCSS('color', 'rgb(0, 0, 0)')
  await expect(help.locator('.support-log-line')).toHaveCount(3)
  await page.screenshot({ path: testInfo.outputPath('win98-recovery.png') })
  await help.getByRole('button', { name: 'Close', exact: true }).click()
  await expect(input).toHaveValue('my unsent draft')
})

test('enabled and disabled choices survive reload while discovery stays available', async ({ page }) => {
  await gotoApp(page)
  await unlock(page)
  await page.reload()
  await expect(page.locator('.role-card')).toHaveCount(2)
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'win98')
  const settings = await appearance(page)
  const toggle = settings.getByRole('switch', { name: /Windows 98/ })
  await toggle.uncheck()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'default')
  const reopened = await appearance(page)
  await expect(reopened.getByRole('switch', { name: /Windows 98/ })).not.toBeChecked()
  await reopened.getByRole('switch', { name: /Windows 98/ }).check()
  await expect(page.locator('html')).toHaveAttribute('data-skin', 'win98')
})

test('narrow Win98 workspace keeps chat, identity and recovery within the viewport', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 430, height: 860 })
  await gotoApp(page)
  await unlock(page)
  await page.locator('.compact-role-controls').click()
  await expect(page.locator('.runtime-role--open')).toHaveCSS('border-radius', '0px')
  await expect(page.locator('.runtime-role--open select').first()).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false)
  await page.screenshot({ path: testInfo.outputPath('win98-narrow-chat.png') })
  await page.getByRole('button', { name: 'Help & recovery', exact: true }).click()
  const help = page.locator('.workspace-help')
  await expect(help).toHaveCSS('border-radius', '0px')
  expect(await help.evaluate(element => element.scrollWidth > element.clientWidth + 1)).toBe(false)
  await expect(help.getByRole('button', { name: 'Close', exact: true })).toBeInViewport()
  await page.screenshot({ path: testInfo.outputPath('win98-narrow-recovery.png') })
})
